// The English dictionary, and the key list every other locale is checked against.
//
// Two groups live here. The strings an annotator reads while working (actions, the editor, the tool strip),
// and the navigation shell around them: the sidebar and menu labels, common buttons, the loading and error
// states, the command palette, the account menu and the home page. A person has to be able to find the
// queue before the words inside it matter.
//
// The governance and platform pages themselves stay English on purpose: they are read by operators who
// configured the deployment, and a half-translated compliance page is worse than an English one because it
// invites the reader to trust a phrasing nobody reviewed for legal meaning. Their names in the sidebar are
// translated; their contents are not.
//
// Data is never translated. Class names, session ids and model versions stay as they are, because
// renaming a class in the interface would make it impossible to talk about with the ontology.

